-- MySQL에서 1회 실행한다. 기존 데이터는 삭제하지 않는다.
CREATE DATABASE IF NOT EXISTS post_test CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE post_test;
CREATE TABLE IF NOT EXISTS posts (
    post_no BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    writer VARCHAR(50) NOT NULL,
    content TEXT NOT NULL,
    reg_date DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    upd_date DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
